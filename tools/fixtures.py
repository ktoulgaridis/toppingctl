#!/usr/bin/env python3
"""Builds tests/fixtures/frames.tsv from the recorded captures (#8).

For every (direction, group, param) seen in captures/*/*.txt it keeps up to
three frames with distinct values (first occurrences), padded to the 16-byte
HID report. Output columns: dir, frame hex, source file.

Usage: python3 tools/fixtures.py > tests/fixtures/frames.tsv
"""
import glob
import os
import sys

PER_KEY = 3
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
seen = {}
for path in sorted(glob.glob(os.path.join(root, 'captures', '*', '*.txt'))):
    rel = os.path.relpath(path, root)
    with open(path) as f:
        for line in f:
            parts = line.split()
            if len(parts) < 16 or parts[1] not in ('tx', 'rx'):
                continue
            frame = parts[2:18] if len(parts) >= 18 and len(parts[17]) == 2 else parts[2:17]
            frame = (frame + ['00'])[:16]
            key = (parts[1], frame[5], frame[6])
            vals = seen.setdefault(key, {})
            value = ''.join(frame[7:13])  # value + crc bytes: tx with/without CRC both kept
            if value not in vals and len(vals) < PER_KEY:
                vals[value] = (' '.join(frame), rel)

out = sys.stdout
out.write('# dir\tframe (16-byte report)\tsource  -- generated by tools/fixtures.py, do not edit\n')
for key in sorted(seen):
    for frame, rel in seen[key].values():
        out.write(f'{key[0]}\t{frame}\t{rel}\n')
